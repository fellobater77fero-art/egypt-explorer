export function transliterateNameToHieroglyphs(name: string): {
  glyphs: string;
  breakdown: { char: string; glyph: string; code: string; sound: string }[];
} {
  const clean = name.trim().toLowerCase();
  const breakdown: { char: string; glyph: string; code: string; sound: string }[] = [];
  let glyphs = '';

  for (const ch of clean) {
    if (ch === ' ' || ch === '-') {
      continue;
    }
    const match = PHONETIC_MAPPING[ch];
    if (match) {
      breakdown.push({ char: ch.toUpperCase(), glyph: match.glyph, code: match.code, sound: match.sound });
      glyphs += match.glyph;
    }
  }

  return { glyphs, breakdown };
}

